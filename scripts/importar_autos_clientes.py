def norm(s):
    """Normaliza un encabezado para el mapeo de aliases (sin tildes, mayúsculas)."""
    import unicodedata

    s = unicodedata.normalize("NFD", str(s or ""))
    s = "".join(c for c in s if unicodedata.category(c) != "Mn")
    return s.strip().lower().replace(" ", "_").replace("-", "_")


def derive_key(key_str):
    return hashlib.sha256(key_str.encode()).digest()


def encrypt(aes_key, plaintext):
    if not plaintext:
        return plaintext
    nonce = os.urandom(12)
    ct = AESGCM(aes_key).encrypt(nonce, plaintext.encode("utf-8"), None)
    return "v1:%s:%s" % (
        base64.b64encode(nonce).decode(),
        base64.b64encode(ct).decode(),
    )


def try_decrypt(aes_key, valor):
    """Descifra v1:... Devuelve (ok, texto)."""
    if not valor.startswith("v1:"):
        return True, valor
    try:
        body = valor[3:]
        nonce_b64, ct_b64 = body.split(":", 1)
        plain = AESGCM(aes_key).decrypt(
            base64.b64decode(nonce_b64), base64.b64decode(ct_b64), None
        )
        return True, plain.decode("utf-8")
    except Exception:  # noqa: BLE001
        return False, valor


def cifrar_pii(aes_key, valor, col):
    """Aplica la política PII de importación descrita en la cabecera."""
    if valor is None or valor == "":
        return None, ""
    if not isinstance(valor, str):
        valor = str(valor)
    if valor.startswith("v1:"):
        ok, claro = try_decrypt(aes_key, valor)
        if not ok:
            return valor, "v1-ajeno-conservado"
        # Roundtrip: re-cifrar con la clave destino (coherencia garantizada).
        return encrypt(aes_key, claro), ""
    return encrypt(aes_key, valor), ""


# ── Parser del dump SQL ────────────────────────────────────────────────────

def parse_sql_inserts(texto):
    """Extrae sentencias INSERT INTO <tabla> (...) VALUES (...) del texto.

    Devuelve [(tabla_mayus, {col: valor_python}, numero_linea)]. El parser
    respeta comillas simples ('') y paréntesis anidados dentro de los valores.
    Cualquier otra sentencia del dump (CREATE, ALTER, COMMIT...) se ignora.
    """
    resultado = []
    i = 0
    n = len(texto)
    while i < n:
        # Buscar "insert into" (case-insensitive)
        m = texto[i:].lower().find("insert into")
        if m == -1:
            break
        i += m + len("insert into")
        # Nombre de tabla
        j = i
        while j < n and texto[j] in " \t":
            j += 1
        tabla = ""
        while j < n and (texto[j].isalnum() or texto[j] in "_\"\""):
            if texto[j] not in '"':
                tabla += texto[j]
            j += 1
        tabla = tabla.strip().upper()
        if tabla not in ("AUTOS", "CLIENTES"):
            i = j
            continue
        # Columnas entre paréntesis
        j = skip_ws(texto, j)
        if j >= n or texto[j] != "(":
            i = j
            continue
        cols, j = read_parenthesis(texto, j)
        # VALUES
        j = skip_ws(texto, j)
        if texto[j:j + 6].lower() != "values":
            i = j
            continue
        j = skip_ws(texto, j + 6)
        if j >= n or texto[j] != "(":
            i = j
            continue
        vals, j = read_parenthesis(texto, j)
        cols = [c.strip().strip('"').upper() for c in cols]
        vals_parsed = [parse_sql_value(v.strip()) for v in vals]
        resultado.append((tabla, dict(zip(cols, vals_parsed)), None))
        i = j
    return resultado


def skip_ws(texto, i):
    n = len(texto)
    while i < n and texto[i] in " \t\r\n":
        i += 1
    return i


def read_parenthesis(texto, i):
    """Lee un paréntesis balanceado respetando comillas simples. Devuelve
    (lista_de_fragmentos_top_level, pos_tras_cierre)."""
    i += 1  # abrir (
    n = len(texto)
    frags = []
    cur = []
    depth = 1
    in_str = False
    while i < n:
        c = texto[i]
        if in_str:
            cur.append(c)
            if c == "'":
                if i + 1 < n and texto[i + 1] == "'":
                    cur.append("'")
                    i += 2
                    continue
                in_str = False
            i += 1
            continue
        if c == "'":
            in_str = True
            cur.append(c)
            i += 1
            continue
        if c == "(":
            depth += 1
            cur.append(c)
            i += 1
            continue
        if c == ")":
            depth -= 1
            if depth == 0:
                frags.append("".join(cur))
                return frags, i + 1
            cur.append(c)
            i += 1
            continue
        if c == "," and depth == 1:
            frags.append("".join(cur))
            cur = []
            i += 1
            continue
        cur.append(c)
        i += 1
    raise ValueError("paréntesis sin cerrar en el dump SQL")


def parse_sql_value(v):
    """Convierte un literal SQL a valor Python (None / str / num / fecha)."""
    if v == "":
        return None
    if v.upper() == "NULL":
        return None
    if v.startswith("'"):
        # string SQL: '' -> '
        s = v[1:-1].replace("''", "'")
        # Fechas/timestamps textuales de Firebird. SOLO con formato ISO estricto
        # (YYYY-MM-DD): desde Python 3.11+ fromisoformat acepta formatos compactos
        # (YYYYMMDD) y en 3.14 convierte '1052070892' -> date(1052,7,8), corrompiendo
        # columnas string numéricas como no_doc. Sin guiones -> nunca fecha.
        s2 = s.strip()
        if len(s2) == 10 and s2[4] == "-" and s2[7] == "-":
            try:
                return datetime.date.fromisoformat(s2)
            except ValueError:
                pass
        # Datetime solo si trae componente de hora (T o espacio + hora:min).
        s3 = s2.replace(" ", "T")
        if "T" in s3 and ":" in s3:
            try:
                return datetime.datetime.fromisoformat(s3)
            except ValueError:
                pass
        return s
    # Números
    try:
        if "." in v or "," in v.replace(",", "."):
            return float(v.replace(",", "."))
        return int(v)
    except ValueError:
        return v


# ── Lectura de Excel ───────────────────────────────────────────────────────

def leer_excel(path, hoja_autos, hoja_clientes):
    from openpyxl import load_workbook

    wb = load_workbook(path, data_only=True)
    tablas = {}
    for hoja, nombre_tabla in ((hoja_autos, "AUTOS"), (hoja_clientes, "CLIENTES")):
        ws = wb[hoja] if hoja else wb.worksheets[0]
        filas = list(ws.iter_rows(values_only=True))
        if not filas:
            tablas[nombre_tabla] = []
            continue
        headers = [norm(h) for h in filas[0]]
        map_col = {}
        for idx, h in enumerate(headers):
            if h in ALIASES:
                map_col[idx] = ALIASES[h]
        filas_out = []
        for row in filas[1:]:
            if row is None or all(c is None or str(c).strip() == "" for c in row):
                continue
            rec = {}
            for idx, col in map_col.items():
                val = row[idx] if idx < len(row) else None
                if val is not None and isinstance(val, str) and val.strip() == "":
                    val = None
                rec[col] = val
            filas_out.append(rec)
        tablas[nombre_tabla] = filas_out
    wb.close()
    return tablas


# ── Upsert ─────────────────────────────────────────────────────────────────

def upsert_autos(cur, filas, aes_key, reporte, quiet):
    cols = COLS_AUTOS
    for rec in filas:
        placa = (rec.get("PLACA") or "").strip().upper()
        if not placa:
            reporte["autos_saltados"] += 1
            if not quiet:
                print("  ! auto sin placa (saltado): %r" % (rec,))
            continue
        cur.execute("SELECT COUNT(*) FROM autos WHERE placa = ?", (placa,))
        existe = cur.fetchone()[0] > 0
        # Valores: solo columnas presentes; defaults para el resto.
        vals = []
        colset = []
        for c in cols:
            if c in rec and rec[c] is not None:
                colset.append(c)
                vals.append(rec[c])
        if "PLACA" not in colset:
            colset.append("PLACA")
            vals.append(placa)
        colset.append("UPDATED_AT")
        vals.append(datetime.datetime.now())
        if not existe:
            colset.append("CREATED_AT")
            vals.append(datetime.datetime.now())
        ph = ", ".join("?" for _ in colset)
        sql = "UPDATE OR INSERT INTO autos (%s) VALUES (%s) MATCHING (PLACA)" % (
            ", ".join(colset), ph,
        )
        cur.execute(sql, vals)
        if existe:
            reporte["autos_actualizados"] += 1
            if not quiet:
                print("  ~ auto %s actualizado" % placa)
        else:
            reporte["autos_nuevos"] += 1
            if not quiet:
                print("  + auto %s nuevo" % placa)


def upsert_clientes(cur, filas, aes_key, reporte, quiet):
    cols = COLS_CLIENTES
    for rec in filas:
        no_doc = (rec.get("NO_DOC") or "").strip()
        nombres = (rec.get("NOMBRES") or "").strip()
        nombre_completo = (rec.get("NOMBRE_COMPLETO") or "").strip()
        if not nombres and not nombre_completo:
            reporte["clientes_saltados"] += 1
            if not quiet:
                print("  ! cliente sin nombres (saltado): %r" % (rec,))
            continue
        if not nombre_completo:
            nombre_completo = "%s %s" % (
                nombres, (rec.get("APELLIDOS") or "").strip(),
            )
            nombre_completo = " ".join(nombre_completo.split())
            rec["NOMBRE_COMPLETO"] = nombre_completo
        # Cifrado PII
        avisos = {}
        for col in COLS_PII:
            if col in rec and rec[col] is not None:
                rec[col], nota = cifrar_pii(aes_key, rec[col], col)
                if nota:
                    avisos[col] = nota
        # Existe por no_doc?
        existe = False
        if no_doc:
            cur.execute("SELECT COUNT(*) FROM clientes WHERE no_doc = ?", (no_doc,))
            existe = cur.fetchone()[0] > 0
        vals = []
        colset = []
        for c in cols:
            if c in rec and rec[c] is not None:
                colset.append(c)
                vals.append(rec[c])
        colset.append("UPDATED_AT")
        vals.append(datetime.datetime.now())
        if not existe:
            colset.append("CREATED_AT")
            vals.append(datetime.datetime.now())
        if existe and no_doc:
            cur.execute(
                "UPDATE clientes SET %s WHERE no_doc = ?"
                % ", ".join("%s = ?" % c for c in colset),
                vals + [no_doc],
            )
            reporte["clientes_actualizados"] += 1
            if not quiet:
                print("  ~ cliente %s actualizado%s"
                      % (nombre_completo, avisos and " (%s)" % ",".join(avisos) or ""))
        else:
            ph = ", ".join("?" for _ in colset)
            cur.execute(
                "INSERT INTO clientes (%s) VALUES (%s)" % (", ".join(colset), ph),
                vals,
            )
            reporte["clientes_nuevos"] += 1
            if not quiet:
                print("  + cliente %s nuevo%s"
                      % (nombre_completo, avisos and " (%s)" % ",".join(avisos) or ""))


