-- 0001_initial_schema.sql
-- Esquema inicial Dinamo Rent ERP — dialecto Firebird 5.0
-- Extraído del .fdb de producción (ODS 13.1). Orden de creación respeta FKs.
--
-- IDEMPOTENCIA (auto-reparación de instalaciones nuevas): cada CREATE TABLE /
-- CREATE INDEX va envuelto en un EXECUTE BLOCK que comprueba primero en el
-- catálogo (RDB$RELATIONS / RDB$INDICES) si el objeto ya existe. Si una
-- instalación nueva se interrumpió a mitad (crash, corte de luz) y la migración
-- no quedó registrada en schema_migrations, el siguiente arranque la reintenta:
-- los guards omiten lo ya creado y crean lo que falta. Las comillas simples de
-- los DEFAULT se duplican (''...) por ir dentro del literal de EXECUTE
-- STATEMENT.
--
-- Consolidación de índices (0010/0011): esta migración ya NO crea los índices
-- que duplican a otros — los cubren los compuestos y el índice automático de
-- las FKs, y 0011 los elimina de las BDs existentes:
--   IX_RENTAS_PLACA, IX_RENTAS_ID_CLIENTE, IX_RENTAS_ESTADO,
--   IX_GASTOS_PLACA, IX_MANTENIMIENTO_VEHICULOS_PLACA.

